#!/usr/bin/env bash
# 命令行文案语言。默认英文；--zh 会把 OUTPUT_LANG 设为 zh。

: "${OUTPUT_LANG:=en}"
if [ "${OUTPUT_LANG}" != "zh" ]; then
    OUTPUT_LANG="en"
fi
export OUTPUT_LANG

# -----------------------------------------------------------------------------
# 函数: t
# 作用: 按当前语言返回文案，不追加换行。
# 入参:
#   $1 -> 英文
#   $2 -> 中文
# -----------------------------------------------------------------------------
t() {
    if [ "${OUTPUT_LANG}" = "zh" ]; then
        printf '%s' "$2"
    else
        printf '%s' "$1"
    fi
}

# -----------------------------------------------------------------------------
# 函数: say
# 作用: 按当前语言打印一行文案。
# 入参:
#   $1 -> 英文
#   $2 -> 中文
# -----------------------------------------------------------------------------
say() {
    t "$@"
    printf '\n'
}
